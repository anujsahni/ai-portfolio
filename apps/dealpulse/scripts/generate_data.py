#!/usr/bin/env python3
"""MVP-03: generate the synthetic Salesforce data, check it, report on it and (optionally) upload it.

Usage: python scripts/generate_data.py [--seed 7] [--out data/out] [--upload] [--report PATH]
Upload goes to the stack's data bucket as the operator: crm-snapshot/, training/, knowledge/.
The eval/ folder (hidden truth, traps) stays local.
"""
from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dealpulse.datagen import checks, output  # noqa: E402
from dealpulse.datagen.generator import Generator  # noqa: E402
from dealpulse.datagen.vocab import OPEN_STAGES, SNAPSHOT_DATE  # noqa: E402

TARGETS = {  # design §3 volumes (±10% is the acceptance band)
    "Account": 400, "User": 8, "Opportunity": 2460, "OpportunityHistory": 15000, "Contact": 1500,
    "OpportunityContactRole": 6000, "Case": 300, "open deals": 60, "accounts with open deals": 40,
    "notes on open deals": 700, "training rows": 12000,
}


def pct(n: float, d: float) -> str:
    return f"{100 * n / d:.1f}%" if d else "—"


def seed_spread(rule: dict, scenarios: list[dict], seeds=range(1, 13)) -> str:
    """How much key volumes vary with the seed (the design targets are approximate)."""
    import statistics
    notes, wins = [], []
    for seed in seeds:
        ds = Generator(seed, rule, scenarios).generate()
        notes.append(sum(1 for k in ("Task", "Event") for r in ds.objects[k] if r.get("Description")))
        closed = [t for t in ds.truth if t["closed"]]
        wins.append(sum(t["won"] for t in closed) / len(closed))
    return (f"Across seeds {seeds.start}–{seeds.stop - 1}: notes on open deals average {statistics.mean(notes):.0f} "
            f"(range {min(notes)}–{max(notes)}), win rate {100 * min(wins):.1f}–{100 * max(wins):.1f}%. "
            "The default seed (1) was chosen because it sits near the average.")


def report(ds, info: dict, problems: dict[str, list[str]], seed: int, out: Path, spread: str = "") -> str:
    objs = ds.objects
    opps = objs["Opportunity"]
    open_ = [o for o in opps if not o["IsClosed"]]
    closed = [t for t in ds.truth if t["closed"]]
    notes = [r for k in ("Task", "Event") for r in objs[k] if r.get("Description")]
    actual = {k: len(v) for k, v in objs.items()}
    actual.update({"open deals": len(open_), "accounts with open deals": len({o["AccountId"] for o in open_}),
                   "notes on open deals": len(notes), "training rows": info["training_rows"]})

    lines = [
        "# MVP-03 evidence — synthetic data summary", "",
        f"Generated by `make data` (seed {seed}, snapshot date {SNAPSHOT_DATE}). All companies, people, deals and notes are fictional.", "",
        "## Volumes vs. design targets", "",
        "| Object | Target | Actual | Within ±10% |", "|---|---|---|---|",
    ]
    for name, target in TARGETS.items():
        got = actual.get(name, 0)
        lines.append(f"| {name} | {target:,} | {got:,} | {'✓' if abs(got - target) <= 0.1 * target else '✗'} |")
    if spread:
        lines += ["", spread]
    lines += ["", f"Also: {len(objs['Task']):,} tasks and {len(objs['Event']):,} events in total "
              f"(open-deal ones carry notes), {len(objs['OpportunityFieldHistory']):,} field-history rows.", ""]

    won = sum(t["won"] for t in closed)
    lines += ["## Outcomes (closed deals)", "", f"Overall win rate: **{pct(won, len(closed))}** ({won:,} of {len(closed):,}).", "",
              "| Group | Deals | Win rate |", "|---|---|---|"]
    for label, key in (("Segment", "segment"), ("Deal type", "deal_type")):
        for value in sorted({t[key] for t in closed}):
            group = [t for t in closed if t[key] == value]
            lines.append(f"| {label}: {value} | {len(group):,} | {pct(sum(t['won'] for t in group), len(group))} |")
    for label, flag in (("Executive engaged", "exec_engaged"), ("Champion", "champion")):
        for value in (True, False):
            group = [t for t in closed if t[flag] == value]
            lines.append(f"| {label}: {'yes' if value else 'no'} | {len(group):,} | {pct(sum(t['won'] for t in group), len(group))} |")
    for value in (False, True):
        group = [t for t in closed if bool(t["competitor"]) == value]
        lines.append(f"| Competitor: {'yes' if value else 'no'} | {len(group):,} | {pct(sum(t['won'] for t in group), len(group))} |")
    lines += ["", "Lost deals by furthest stage reached:", "", "| Stage | Lost deals |", "|---|---|"]
    lost_stage = Counter(OPEN_STAGES[t["stage_index"]] for t in closed if not t["won"])
    lines += [f"| {s} | {lost_stage.get(s, 0):,} |" for s in OPEN_STAGES]

    with (out / "training" / "rows.csv").open() as fh:
        rows = list(csv.DictReader(fh))
    lines += ["", "## Training rows", "",
              f"{len(rows):,} point-in-time snapshots of closed deals (every 18 days while open); "
              f"{pct(sum(r['is_won'] == '1' for r in rows), len(rows))} labelled won. Quarters: "
              + ", ".join(f"{q} {n:,}" for q, n in sorted(Counter(r['close_quarter'] for r in rows).items())) + "."]

    lines += ["", "## Open pipeline (this quarter)", "", "| Stage | Deals | Commit | Best Case | Pipeline |", "|---|---|---|---|---|"]
    for s in OPEN_STAGES:
        group = [o for o in open_ if o["StageName"] == s]
        fc = Counter(o["ForecastCategoryName"] for o in group)
        lines.append(f"| {s} | {len(group)} | {fc['Commit']} | {fc['Best Case']} | {fc['Pipeline']} |")
    topics = Counter(t["topic"] for t in ds.note_topics)
    lines += ["", "Note topics: " + ", ".join(f"{k} {v}" for k, v in topics.most_common()) + "."]

    lines += ["", "## Knowledge documents", "",
              f"8 playbook sections, 4 pricing-policy sections (hand-written, `data/playbooks/`), {info['reviews']} anonymised win/loss reviews.", ""]

    sc = ds.traps["scenarios"]
    lines += ["## Scripted scenarios and test traps", "", "| Key | Opportunity | Purpose |", "|---|---|---|"]
    specs = {s["key"]: s for s in json.loads((ROOT / "data/generator/scenarios.json").read_text())["scenarios"]}
    lines += [f"| {k} | `{v}` | {specs[k]['purpose']} |" for k, v in sc.items()]
    lines += ["", f"Injection note: `{ds.traps['injection']['ActivityId']}` on `{ds.traps['injection']['OpportunityId']}`.", ""]

    lines += ["## Checks", "", "| Check | Result |", "|---|---|"]
    for name, found in problems.items():
        lines.append(f"| {name} | {'✓ pass' if not found else '✗ ' + str(len(found)) + ' problems: ' + found[0]} |")
    return "\n".join(lines) + "\n"


def upload(out: Path) -> None:
    outputs = json.loads(subprocess.run(["terraform", f"-chdir={ROOT / 'infra/stack'}", "output", "-json"],
                                        check=True, capture_output=True, text=True).stdout)
    bucket = outputs["data_bucket"]["value"]
    for prefix in ("crm-snapshot", "training", "knowledge"):
        subprocess.run(["aws", "s3", "sync", str(out / prefix), f"s3://{bucket}/{prefix}", "--delete", "--only-show-errors"], check=True)
        count = sum(1 for p in (out / prefix).rglob("*") if p.is_file())
        print(f"  ↑ s3://{bucket}/{prefix}/ ({count} files)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--scale", type=float, default=1.0, help="shrink for quick tests (1.0 = design volumes)")
    parser.add_argument("--out", type=Path, default=ROOT / "data" / "out")
    parser.add_argument("--upload", action="store_true")
    parser.add_argument("--report", type=Path, default=ROOT / "docs/mvp/evidence/MVP-03-data-summary.md")
    args = parser.parse_args()

    rule = json.loads((ROOT / "data/generator/hidden_rule.json").read_text())
    scenarios = json.loads((ROOT / "data/generator/scenarios.json").read_text())["scenarios"]
    ds = Generator(args.seed, rule, scenarios, scale=args.scale).generate()
    info = output.write(ds, args.out, seed=args.seed, rule=rule)

    problems = {
        "Referential integrity (every foreign key resolves; open deals have contact roles)": checks.referential_integrity(ds.objects),
        "Notes agree with each open deal's drivers": checks.notes_agree_with_drivers(ds.objects, ds.truth),
        "Contact details are fictional (example.com, 555-01xx)": checks.contact_details_are_fictional(ds.objects),
        "All four traps present": [] if all([ds.traps.get("injection"), ds.traps.get("discount_35"), ds.traps.get("thin_notes"),
                                             ds.traps["lookalike"]["approved"]["OpportunityId"],
                                             ds.traps["lookalike"]["not_approved"]["OpportunityId"]]) else ["missing trap"],
    }
    spread = seed_spread(rule, scenarios) if args.scale == 1.0 else ""
    text = report(ds, info, problems, args.seed, args.out, spread)
    if args.scale == 1.0:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(text)
        print(f"✓ report: {args.report.relative_to(ROOT)}")
    print(f"✓ wrote {info['files']} files to {args.out} ({info['training_rows']:,} training rows, {info['reviews']} reviews)")
    failed = {k: v for k, v in problems.items() if v}
    for name, found in failed.items():
        print(f"✗ {name}: {len(found)} problems, e.g. {found[0]}")
    if failed:
        return 1
    print("✓ all data checks pass")
    if args.upload:
        upload(args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
